import { esc } from './util.js';

/* ==========================================================================
   Visualization renderers. Each one draws the state of a frame produced by
   player.buildFrames() from the REAL step list generated by the C++ engine.
   ========================================================================== */

const legendHtml = (items) => `<div class="legend">${items.map(([c, t]) => `<span><i style="background:${c}"></i>${t}</span>`).join('')}</div>`;
const C = {
  default: 'color-mix(in srgb, var(--accent) 38%, var(--surface-3))',
  cmp: 'var(--accent)', swap: 'var(--warn)', sorted: 'var(--accent-2)', pivot: 'var(--danger)', min: 'var(--info)',
  dim: 'var(--surface-3)'
};

/* ----------------------------- bars (sorting) ----------------------------- */
function barsRenderer(root, ctx) {
  const W = 900, PAD = 22, TOP = 40, MAIN_H = 220;
  const hasAux = ctx.algorithmId === 'merge_sort';
  const H = TOP + MAIN_H + 40 + (hasAux ? 118 : 0);
  const initial = ctx.frames[0].view.arr || [];
  const lo = Math.min(0, ...initial), hi = Math.max(0, ...initial);
  const span = hi - lo || 1;
  const scale = MAIN_H / span;
  const zeroY = TOP + hi * scale;
  const n = initial.length;
  const slot = (W - 2 * PAD) / n;
  const bw = Math.min(slot * 0.78, 58);
  const showVals = n <= 32;
  const fs = n > 24 ? 9 : 11;

  let html = `<svg class="bars-svg" viewBox="0 0 ${W} ${H}" role="img" aria-label="Array bars"><line x1="${PAD}" x2="${W - PAD}" y1="${zeroY}" y2="${zeroY}" stroke="var(--border-strong)"/>`;
  for (let i = 0; i < n; i += 1) {
    const x = PAD + i * slot + (slot - bw) / 2;
    html += `<rect class="bar" data-b="${i}" x="${x}" width="${bw}" rx="3"/>`;
    if (showVals) html += `<text data-v="${i}" x="${x + bw / 2}" text-anchor="middle" style="font-size:${fs}px"></text>`;
    if (n <= 40) html += `<text x="${x + bw / 2}" y="${TOP + MAIN_H + 18}" text-anchor="middle" style="font-size:${fs - 1}px;opacity:.55">${i}</text>`;
  }
  if (hasAux) {
    html += `<text x="${PAD}" y="${TOP + MAIN_H + 52}" style="font-size:11px;opacity:.75">temporary merge buffer</text>`;
    for (let i = 0; i < n; i += 1) {
      const x = PAD + i * slot + (slot - bw) / 2;
      html += `<rect class="bar" data-a="${i}" x="${x}" width="${bw}" rx="3" opacity="0"/>`;
      if (showVals) html += `<text data-av="${i}" x="${x + bw / 2}" text-anchor="middle" style="font-size:${fs}px"></text>`;
    }
  }
  html += `<text data-key x="${PAD}" y="22" style="font-size:13px;font-weight:600;fill:var(--accent)"></text><text data-range x="${W - PAD}" y="22" text-anchor="end" style="font-size:12px;opacity:.75"></text></svg>`;
  root.innerHTML = html;

  const bars = [...root.querySelectorAll('[data-b]')];
  const vals = [...root.querySelectorAll('[data-v]')];
  const abars = [...root.querySelectorAll('[data-a]')];
  const avals = [...root.querySelectorAll('[data-av]')];
  const keyEl = root.querySelector('[data-key]');
  const rangeEl = root.querySelector('[data-range]');
  const auxTop = TOP + MAIN_H + 62, auxH = 52;
  const maxAbs = Math.max(1, ...initial.map(Math.abs));

  return {
    legend: legendHtml([[C.cmp, 'comparing'], [C.swap, 'swapped / written'], [C.sorted, 'sorted'], [C.pivot, 'pivot'], [C.min, 'current minimum']]),
    update(frame) {
      const v = frame.view;
      const arr = v.arr || initial;
      const sorted = new Set(v.sorted || []);
      const cmp = new Set([...(v.cmp || [])]);
      const hot = new Set([...(v.swap || []), ...(v.set || [])]);
      const [rlo, rhi] = v.range || [0, n - 1];
      const heap = v.heapSize;
      for (let i = 0; i < n; i += 1) {
        const val = arr[i];
        const h = Math.max(3, Math.abs(val) * scale);
        const y = val >= 0 ? zeroY - h : zeroY;
        const b = bars[i];
        b.setAttribute('y', y);
        b.setAttribute('height', h);
        let fill = C.default;
        let opacity = 1;
        if (v.range && (i < rlo || i > rhi)) opacity = 0.35;
        if (typeof heap === 'number' && i >= heap && !sorted.has(i)) opacity = 0.45;
        if (sorted.has(i)) fill = C.sorted;
        if (v.min === i) fill = C.min;
        if (cmp.has(i)) fill = C.cmp;
        if (hot.has(i)) fill = C.swap;
        if (v.pivot === i) fill = C.pivot;
        b.style.fill = fill;
        b.style.opacity = opacity;
        if (vals[i]) {
          vals[i].textContent = val;
          vals[i].setAttribute('y', val >= 0 ? y - 5 : y + h + 12);
        }
      }
      keyEl.textContent = typeof v.key === 'number' ? `key = ${v.key}` : '';
      rangeEl.textContent = v.range ? `active range [${rlo}..${rhi}]` : (typeof heap === 'number' ? `heap size ${heap}` : '');
      if (hasAux) {
        const aux = v.aux;
        const [alo] = v.auxRange || [0, -1];
        const cmpAux = new Set(v.cmpAux || []);
        for (let i = 0; i < n; i += 1) {
          const inside = aux && i >= alo && i < alo + aux.length;
          const rect = abars[i];
          if (!inside) { rect.setAttribute('opacity', 0); if (avals[i]) avals[i].textContent = ''; continue; }
          const val = aux[i - alo];
          const h = Math.max(3, (Math.abs(val) / maxAbs) * auxH);
          rect.setAttribute('opacity', 1);
          rect.setAttribute('y', auxTop + auxH - h);
          rect.setAttribute('height', h);
          rect.style.fill = cmpAux.has(i) ? C.cmp : 'color-mix(in srgb, var(--accent-2) 45%, var(--surface-3))';
          if (avals[i]) { avals[i].textContent = val; avals[i].setAttribute('y', auxTop + auxH - h - 5); }
        }
      }
    }
  };
}

/* ----------------------------- cells (searching) --------------------------- */
function cellsRenderer(root, ctx) {
  const target = ctx.input.target;
  return {
    legend: legendHtml([[C.cmp, 'being checked'], ['var(--ok)', 'found'], ['var(--warn)', 'current block'], [C.dim, 'eliminated']]),
    update(frame) {
      const v = frame.view;
      const arr = v.arr || ctx.input.array;
      const hasWindow = typeof v.low === 'number';
      const cmp = new Set(v.cmp || []);
      const [b0, b1] = v.block || [-1, -2];
      const status = v.found === null || v.found === undefined ? 'searching' : v.found >= 0 ? `found at index ${v.found}` : 'not found';
      const cells = arr.map((val, i) => {
        const cls = ['cell'];
        if (hasWindow) cls.push(i < v.low || i > v.high ? 'dim' : 'window');
        if (i >= b0 && i <= b1) cls.push('block');
        if (cmp.has(i)) cls.push('cmp');
        if (v.found === i) cls.push('found');
        const tags = [];
        if (hasWindow && i === v.low) tags.push('low');
        if (hasWindow && i === v.high) tags.push('high');
        if (hasWindow && i === v.mid) tags.push('mid');
        return `<div class="cell-wrap"><div class="${cls.join(' ')}">${tags.length ? `<span class="tag">${tags.join('/')}</span>` : ''}${val}<small>${i}</small></div></div>`;
      }).join('');
      root.innerHTML = `<div class="row between" style="margin-bottom:26px"><span class="chip accent">target = ${target}</span><span class="chip ${v.found >= 0 ? 'teal' : v.found === -1 ? 'danger' : ''}">${esc(status)}</span></div><div class="cells">${cells}</div>`;
    }
  };
}

/* ----------------------------- graph ---------------------------------------- */
function graphRenderer(root, ctx) {
  const { nodes: n, edges, directed } = ctx.input;
  const weighted = ctx.algorithmId === 'dijkstra';
  const W = 640, H = 430, cx = W / 2, cy = H / 2, R = Math.min(170, 70 + n * 14);
  const pos = Array.from({ length: n }, (_, i) => {
    const a = -Math.PI / 2 + (2 * Math.PI * i) / n;
    return { x: cx + R * Math.cos(a), y: cy + R * Math.sin(a) };
  });
  const frontierLabel = { queue: 'Queue (front → back)', stack: 'Call stack (top at right)', 'priority queue': 'Priority queue (smallest distance first)' };
  return {
    legend: legendHtml([['var(--accent)', 'current node'], ['var(--accent-2)', 'visited'], ['var(--warn)', 'frontier'], ['var(--ok)', 'final path']]),
    update(frame) {
      const v = frame.view;
      const visited = new Set(v.visited || []);
      const frontier = new Set(v.frontier || []);
      const path = v.path || [];
      const pathEdge = new Set();
      for (let i = 0; i + 1 < path.length; i += 1) { pathEdge.add(`${path[i]}-${path[i + 1]}`); if (!directed) pathEdge.add(`${path[i + 1]}-${path[i]}`); }
      const parent = v.parent || [];
      const active = v.edge;
      let svg = `<svg viewBox="0 0 ${W} ${H}" style="max-width:720px;margin:0 auto" role="img" aria-label="Graph"><defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0 10 5 0 10z" fill="currentColor"/></marker></defs>`;
      edges.forEach(([a, b, w]) => {
        const p = pos[a], q = pos[b];
        const dx = q.x - p.x, dy = q.y - p.y, len = Math.hypot(dx, dy) || 1;
        const ux = dx / len, uy = dy / len;
        const x1 = p.x + ux * 22, y1 = p.y + uy * 22, x2 = q.x - ux * (directed ? 26 : 22), y2 = q.y - uy * (directed ? 26 : 22);
        const isActive = active && ((active[0] === a && active[1] === b) || (!directed && active[0] === b && active[1] === a));
        const isPath = pathEdge.has(`${a}-${b}`);
        const isTree = parent[b] === a || (!directed && parent[a] === b);
        const color = isPath ? 'var(--ok)' : isActive ? 'var(--accent)' : isTree ? 'var(--accent-2)' : 'var(--border-strong)';
        const sw = isPath || isActive ? 3.2 : isTree ? 2.2 : 1.5;
        svg += `<g style="color:${color}"><line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${color}" stroke-width="${sw}"${directed ? ' marker-end="url(#arrow)"' : ''}/>`;
        if (weighted) svg += `<g transform="translate(${(p.x + q.x) / 2 - uy * 11} ${(p.y + q.y) / 2 + ux * 11})"><rect x="-11" y="-9" width="22" height="18" rx="5" fill="var(--surface)" stroke="var(--border)"/><text text-anchor="middle" y="4" style="font:600 11px var(--font-mono);fill:var(--text-2)">${w ?? 1}</text></g>`;
        svg += '</g>';
      });
      pos.forEach((p, i) => {
        let fill = 'var(--surface-2)', stroke = 'var(--border-strong)', sw = 1.6, ink = 'var(--text)';
        if (visited.has(i)) { fill = 'color-mix(in srgb, var(--accent-2) 26%, var(--surface-2))'; stroke = 'var(--accent-2)'; }
        if (frontier.has(i)) { stroke = 'var(--warn)'; sw = 3; }
        if (path.includes(i)) { fill = 'color-mix(in srgb, var(--ok) 32%, var(--surface-2))'; stroke = 'var(--ok)'; sw = 3; }
        if (v.current === i) { fill = 'var(--accent)'; stroke = 'var(--accent)'; ink = 'var(--accent-ink)'; }
        svg += `<g><circle class="node-circle" cx="${p.x}" cy="${p.y}" r="21" fill="${fill}" stroke="${stroke}" stroke-width="${sw}"/><text x="${p.x}" y="${p.y + 5}" text-anchor="middle" style="font:700 14px var(--font-mono);fill:${ink}">${i}</text>`;
        if (v.dist) svg += `<text x="${p.x}" y="${p.y + 38}" text-anchor="middle" style="font:600 11px var(--font-mono);fill:var(--text-2)">d=${v.dist[i] === null ? '∞' : v.dist[i]}</text>`;
        if (i === ctx.input.start) svg += `<text x="${p.x}" y="${p.y - 28}" text-anchor="middle" style="font:700 10px var(--font-ui);fill:var(--accent-2);letter-spacing:.06em">START</text>`;
        if (ctx.input.target === i) svg += `<text x="${p.x}" y="${p.y - 28}" text-anchor="middle" style="font:700 10px var(--font-ui);fill:var(--danger);letter-spacing:.06em">TARGET</text>`;
        svg += '</g>';
      });
      svg += '</svg>';
      const tokens = (list, cur) => list.length ? list.map((x) => `<span class="token ${x === cur ? 'cur' : ''}">${x}</span>`).join('') : '<span class="faint">empty</span>';
      let extra = '';
      if (v.dist) extra = `<div class="mini"><h4>Distances</h4><div class="token-row">${v.dist.map((d, i) => `<span class="token ${v.current === i ? 'cur' : ''}">${i}: ${d === null ? '∞' : d}</span>`).join('')}</div></div>`;
      else if (parent.length) extra = `<div class="mini"><h4>Parent of node</h4><div class="token-row">${parent.map((p, i) => `<span class="token">${i}←${p < 0 ? '-' : p}</span>`).join('')}</div></div>`;
      root.innerHTML = `${svg}<div class="side-panel"><div class="mini"><h4>${frontierLabel[v.frontierKind] || 'Frontier'}</h4><div class="token-row">${tokens(v.frontier || [], null)}</div></div><div class="mini"><h4>Visit order</h4><div class="token-row">${tokens(v.visited || [], v.current)}</div></div>${extra}${path.length ? `<div class="mini"><h4>Path</h4><div class="token-row">${path.map((x) => `<span class="token ok">${x}</span>`).join('→')}</div></div>` : ''}</div>`;
    }
  };
}

/* ----------------------------- data structures ------------------------------ */
function listSvg(v, kind) {
  const items = v.items || [];
  const NW = 74, GAP = 46, X0 = 40;
  const W = Math.max(900, X0 * 2 + items.length * (NW + GAP));
  const H = kind === 'clist' ? 210 : 170;
  const y = 70, h = 46;
  let svg = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Linked list"><defs><marker id="la" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0 10 5 0 10z" fill="var(--text-2)"/></marker></defs>`;
  if (!items.length) {
    return `${svg}<text x="${W / 2}" y="${H / 2}" text-anchor="middle" style="font:500 14px var(--font-mono);fill:var(--text-2)">${kind === 'clist' ? 'tail = nullptr (empty list)' : 'head = nullptr (empty list)'}</text></svg>`;
  }
  const x = (i) => X0 + i * (NW + GAP);
  items.forEach((val, i) => {
    const isCur = v.cur === i;
    const isHl = v.hl === i;
    const found = isHl && v.found !== undefined;
    let fill = 'var(--surface-2)', stroke = 'var(--border-strong)';
    if (isHl) { fill = 'color-mix(in srgb, var(--accent) 24%, var(--surface-2))'; stroke = 'var(--accent)'; }
    if (isCur) { fill = 'color-mix(in srgb, var(--warn) 22%, var(--surface-2))'; stroke = 'var(--warn)'; }
    svg += `<g><rect x="${x(i)}" y="${y}" width="${NW}" height="${h}" rx="8" fill="${fill}" stroke="${stroke}" stroke-width="2"/>`;
    if (kind === 'dlist') svg += `<line x1="${x(i) + 14}" x2="${x(i) + 14}" y1="${y}" y2="${y + h}" stroke="${stroke}" opacity=".6"/><line x1="${x(i) + NW - 14}" x2="${x(i) + NW - 14}" y1="${y}" y2="${y + h}" stroke="${stroke}" opacity=".6"/><text x="${x(i) + NW / 2}" y="${y + 29}" text-anchor="middle" style="font:700 15px var(--font-mono);fill:var(--text)">${val}</text>`;
    else svg += `<line x1="${x(i) + NW - 18}" x2="${x(i) + NW - 18}" y1="${y}" y2="${y + h}" stroke="${stroke}" opacity=".6"/><text x="${x(i) + (NW - 18) / 2}" y="${y + 29}" text-anchor="middle" style="font:700 15px var(--font-mono);fill:var(--text)">${val}</text>`;
    svg += `<text x="${x(i) + NW / 2}" y="${y + h + 18}" text-anchor="middle" style="font:400 10px var(--font-mono);fill:var(--text-3)">idx ${i}</text></g>`;
    if (i < items.length - 1) {
      const ax1 = x(i) + NW, ax2 = x(i + 1);
      if (kind === 'dlist') svg += `<line x1="${ax1 + 2}" y1="${y + 16}" x2="${ax2 - 3}" y2="${y + 16}" stroke="var(--text-2)" stroke-width="1.6" marker-end="url(#la)"/><line x1="${ax2 - 2}" y1="${y + 31}" x2="${ax1 + 3}" y2="${y + 31}" stroke="var(--text-2)" stroke-width="1.6" marker-end="url(#la)"/>`;
      else svg += `<line x1="${ax1 - 9}" y1="${y + h / 2}" x2="${ax2 - 3}" y2="${y + h / 2}" stroke="var(--text-2)" stroke-width="1.6" marker-end="url(#la)"/>`;
    }
  });
  const last = items.length - 1;
  if (kind === 'slist') svg += `<text x="${x(last) + NW + 10}" y="${y + 29}" style="font:600 12px var(--font-mono);fill:var(--text-3)">→ NULL</text>`;
  if (kind === 'dlist') svg += `<text x="${x(last) + NW + 8}" y="${y + 20}" style="font:600 11px var(--font-mono);fill:var(--text-3)">next = NULL</text><text x="${x(0) - 6}" y="${y - 22}" text-anchor="end" style="font:600 11px var(--font-mono);fill:var(--text-3)">prev = NULL</text>`;
  if (kind === 'clist') {
    const sx = x(last) + NW / 2, ex = x(0) + NW / 2, by = y + h + 52;
    svg += `<path d="M ${sx} ${y + h + 22} V ${by} H ${ex} V ${y + h + 4}" fill="none" stroke="var(--accent-2)" stroke-width="1.8" marker-end="url(#la)"/><text x="${(sx + ex) / 2}" y="${by + 16}" text-anchor="middle" style="font:600 11px var(--font-mono);fill:var(--accent-2)">tail->next points back to head</text>`;
  }
  const tag = (i, label, color, dy) => `<text x="${x(i) + NW / 2}" y="${y + dy}" text-anchor="middle" style="font:700 11px var(--font-ui);fill:${color};letter-spacing:.06em">${label}</text>`;
  svg += tag(0, 'HEAD', 'var(--accent-2)', -14);
  if (kind !== 'slist') svg += tag(last, 'TAIL', 'var(--accent)', last === 0 ? -30 : -14);
  if (typeof v.cur === 'number' && v.cur >= 0) svg += `<text x="${x(v.cur) + NW / 2}" y="${y - (v.cur === 0 || (kind !== 'slist' && v.cur === last) ? 30 : 14)}" text-anchor="middle" style="font:700 11px var(--font-ui);fill:var(--warn)">cur ▼</text>`;
  return `${svg}</svg>`;
}

function stackSvg(v) {
  const items = v.items || [], cap = v.cap || 6;
  const SW = 200, SH = 40, X = 60, TOPY = 30;
  const H = TOPY + cap * SH + 36;
  let svg = `<svg viewBox="0 0 420 ${H}" style="max-width:420px;margin:0 auto" role="img" aria-label="Stack">`;
  for (let s = 0; s < cap; s += 1) {
    const y = TOPY + (cap - 1 - s) * SH;
    const filled = s < items.length;
    const hl = v.hl === s;
    svg += `<rect x="${X}" y="${y}" width="${SW}" height="${SH - 4}" rx="7" fill="${filled ? (hl ? 'color-mix(in srgb, var(--accent) 30%, var(--surface-2))' : 'var(--surface-2)') : 'transparent'}" stroke="${hl ? 'var(--accent)' : 'var(--border-strong)'}" stroke-width="${hl ? 2.5 : 1.4}" ${filled ? '' : 'stroke-dasharray="5 4"'}/>`;
    svg += `<text x="${X - 10}" y="${y + 24}" text-anchor="end" style="font:400 11px var(--font-mono);fill:var(--text-3)">${s}</text>`;
    if (filled) svg += `<text x="${X + SW / 2}" y="${y + 25}" text-anchor="middle" style="font:700 16px var(--font-mono);fill:var(--text)">${items[s]}</text>`;
  }
  if (items.length) svg += `<text x="${X + SW + 14}" y="${TOPY + (cap - items.length) * SH + 24}" style="font:700 12px var(--font-ui);fill:var(--accent);letter-spacing:.05em">◀ TOP</text>`;
  else svg += `<text x="${X + SW / 2}" y="${TOPY - 10}" text-anchor="middle" style="font:600 12px var(--font-mono);fill:var(--text-3)">empty (top = -1)</text>`;
  return `${svg}</svg>`;
}

function queueSvg(v) {
  const buf = v.buffer || [], cap = v.cap || 5;
  const SW = 78, GAP = 10, X0 = 30;
  const W = Math.max(520, X0 * 2 + cap * (SW + GAP));
  let svg = `<svg viewBox="0 0 ${W} 190" style="max-width:820px;margin:0 auto" role="img" aria-label="Circular queue">`;
  for (let s = 0; s < cap; s += 1) {
    const x = X0 + s * (SW + GAP);
    const used = buf[s] !== null && buf[s] !== undefined;
    const hl = v.hl === s;
    svg += `<rect x="${x}" y="60" width="${SW}" height="52" rx="8" fill="${used ? (hl ? 'color-mix(in srgb, var(--accent) 30%, var(--surface-2))' : 'var(--surface-2)') : 'transparent'}" stroke="${hl ? 'var(--accent)' : 'var(--border-strong)'}" stroke-width="${hl ? 2.5 : 1.4}" ${used ? '' : 'stroke-dasharray="5 4"'}/>`;
    svg += `<text x="${x + SW / 2}" y="${y0(60, 31)}" text-anchor="middle" style="font:700 16px var(--font-mono);fill:var(--text)">${used ? buf[s] : ''}</text>`;
    svg += `<text x="${x + SW / 2}" y="132" text-anchor="middle" style="font:400 11px var(--font-mono);fill:var(--text-3)">slot ${s}</text>`;
    if (v.count > 0 && v.front === s) svg += `<text x="${x + SW / 2}" y="46" text-anchor="middle" style="font:700 11px var(--font-ui);fill:var(--accent-2);letter-spacing:.06em">FRONT ▼</text>`;
    if (v.rear === s) svg += `<text x="${x + SW / 2}" y="${v.count > 0 && v.front === s ? 28 : 46}" text-anchor="middle" style="font:700 11px var(--font-ui);fill:var(--warn);letter-spacing:.06em">${v.count === cap ? 'REAR (full)' : 'NEXT WRITE'} ▼</text>`;
  }
  svg += `<text x="${W / 2}" y="168" text-anchor="middle" style="font:500 12px var(--font-mono);fill:var(--text-2)">count = ${v.count ?? 0} / ${cap}   ·   next write slot = (front + count) mod ${cap}</text></svg>`;
  return svg;
}
const y0 = (base, off) => base + off;

function structureRenderer(root, ctx) {
  return {
    legend: legendHtml([['var(--accent)', 'last changed'], ['var(--warn)', 'pointer position'], [C.sorted, 'found']]),
    update(frame) {
      const v = frame.view;
      const kind = v.kind;
      const upto = ctx.frames.slice(0, ctx.index + 1);
      const ops = [];
      for (const f of upto) { const op = f.view.op; if (op && ops[ops.length - 1] !== op) ops.push(op); }
      const type = frame.step.type;
      const bad = ['overflow', 'underflow', 'error', 'missing'].includes(type);
      let svg;
      if (kind === 'stack') svg = stackSvg(v);
      else if (kind === 'queue') svg = queueSvg(v);
      else svg = listSvg(v, kind);
      const itemsLine = kind === 'queue' ? `Queue (front → rear): [${(v.items || []).join(', ')}]` : kind === 'stack' ? `Stack (bottom → top): [${(v.items || []).join(', ')}]` : `List: [${(v.items || []).join(' → ')}]`;
      root.innerHTML = `<div class="row between" style="margin-bottom:8px"><span class="chip accent">op: ${esc(v.op || '')}</span><span class="chip ${bad ? 'danger' : 'teal'}">${esc(type)}</span></div>${svg}<div class="side-panel"><div class="mini"><h4>Contents</h4><div class="mono" style="font-size:.86rem">${esc(itemsLine)}</div></div><div class="mini"><h4>Operations (${ops.length})</h4><div class="token-row">${ops.map((o, i) => `<span class="token ${i === ops.length - 1 ? 'cur' : ''}">${esc(o)}</span>`).join('')}</div></div></div>`;
    }
  };
}

/* ----------------------------- recursion call tree -------------------------- */
function callTreeRenderer(root) {
  const NW = 78, NH = 32, HG = 12, VG = 52;
  let lastScroll = null;
  return {
    legend: legendHtml([['var(--accent)', 'currently executing'], ['color-mix(in srgb, var(--warn) 55%, var(--surface-3))', 'waiting on the stack'], ['var(--accent-2)', 'returned']]),
    update(frame) {
      const nodes = frame.nodes;
      const stack = frame.view.stack || [];
      if (!nodes.length) { root.innerHTML = '<div class="empty">The call tree grows as the recursion runs.</div>'; return; }
      const kids = new Map();
      nodes.forEach((n) => { if (n.parent >= 0) { if (!kids.has(n.parent)) kids.set(n.parent, []); kids.get(n.parent).push(n.id); } });
      const byId = new Map(nodes.map((n) => [n.id, n]));
      const xs = new Map();
      let leaf = 0;
      const place = (id) => {
        const k = kids.get(id) || [];
        if (!k.length) { xs.set(id, leaf * (NW + HG)); leaf += 1; return; }
        k.forEach(place);
        xs.set(id, (xs.get(k[0]) + xs.get(k[k.length - 1])) / 2);
      };
      place(nodes[0].id);
      const maxDepth = Math.max(...nodes.map((n) => n.depth));
      const W = Math.max(leaf * (NW + HG) + 20, 420), H = (maxDepth + 1) * (NH + VG) + 20;
      const top = stack[stack.length - 1];
      let svg = `<svg width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="Call tree">`;
      nodes.forEach((n) => {
        if (n.parent < 0) return;
        const p = byId.get(n.parent);
        svg += `<line x1="${xs.get(p.id) + NW / 2 + 10}" y1="${p.depth * (NH + VG) + NH + 10}" x2="${xs.get(n.id) + NW / 2 + 10}" y2="${n.depth * (NH + VG) + 10}" stroke="var(--border-strong)" stroke-width="1.6"/>`;
      });
      nodes.forEach((n) => {
        const x = xs.get(n.id) + 10, y = n.depth * (NH + VG) + 10;
        const done = n.value !== null && n.value !== undefined;
        const onStack = stack.includes(n.id);
        let fill = 'var(--surface-2)', stroke = 'var(--border-strong)';
        if (done) { fill = 'color-mix(in srgb, var(--accent-2) 20%, var(--surface-2))'; stroke = 'var(--accent-2)'; }
        if (onStack) { fill = 'color-mix(in srgb, var(--warn) 18%, var(--surface-2))'; stroke = 'var(--warn)'; }
        if (n.id === top) { fill = 'color-mix(in srgb, var(--accent) 35%, var(--surface-2))'; stroke = 'var(--accent)'; }
        svg += `<g class="tnode"><rect x="${x}" y="${y}" width="${NW}" height="${NH}" rx="7" fill="${fill}" stroke="${stroke}" stroke-width="1.8"/><text x="${x + NW / 2}" y="${y + 20}" text-anchor="middle">${esc(n.label)}</text>${done ? `<text class="val" x="${x + NW / 2}" y="${y + NH + 14}" text-anchor="middle">= ${esc(n.value)}</text>` : ''}</g>`;
      });
      svg += '</svg>';
      const frames = stack.map((id) => `<div class="frame ${id === top ? 'top' : ''}">${esc(byId.get(id).label)}</div>`).join('');
      const scrollEl = root.querySelector('.tree-scroll');
      lastScroll = scrollEl ? { left: scrollEl.scrollLeft, top: scrollEl.scrollTop } : null;
      root.innerHTML = `<div class="tree-scroll">${svg}</div><div class="side-panel"><div class="mini"><h4>Call stack (top is highlighted)</h4><div class="callstack">${frames || '<span class="faint">empty</span>'}</div></div><div class="mini"><h4>Calls so far</h4><div class="stat"><span class="v">${nodes.length}</span></div></div></div>`;
      const sc = root.querySelector('.tree-scroll');
      if (top !== undefined && sc) {
        const tx = xs.get(top) + NW / 2 + 10;
        if (tx < (lastScroll ? lastScroll.left : 0) + 40 || tx > (lastScroll ? lastScroll.left : 0) + sc.clientWidth - 40) sc.scrollLeft = Math.max(0, tx - sc.clientWidth / 2);
        else if (lastScroll) sc.scrollLeft = lastScroll.left;
      }
    }
  };
}

/* ----------------------------- gcd -------------------------------------------- */
function gcdRenderer(root) {
  return {
    legend: '',
    update(frame) {
      const v = frame.view;
      const rows = v.rows || [];
      const body = rows.map((r, i) => `<tr class="${i === rows.length - 1 ? 'cur' : ''}"><td>${i + 1}</td><td>${r.a}</td><td>${r.b}</td><td>${r.q}</td><td>${r.r}</td><td style="text-align:left">${r.a} = ${r.b} × ${r.q} + ${r.r}</td></tr>`).join('');
      root.innerHTML = `<div class="table-wrap"><table class="data gcd-table"><thead><tr><th>#</th><th>a</th><th>b</th><th>q = ⌊a/b⌋</th><th>r = a mod b</th><th style="text-align:left">equation</th></tr></thead><tbody>${body || '<tr><td colspan="6" class="faint" style="text-align:left">Press play to start dividing.</td></tr>'}</tbody></table></div>${typeof v.gcd === 'number' ? `<div class="result-banner">gcd = ${v.gcd}</div>` : ''}`;
    }
  };
}

/* ----------------------------- sieve ------------------------------------------ */
function sieveRenderer(root, ctx) {
  const n = ctx.input.n;
  return {
    legend: legendHtml([['var(--ok)', 'prime'], ['var(--warn)', 'being crossed out'], ['var(--accent)', 'current prime'], [C.dim, 'composite']]),
    update(frame) {
      const cells = frame.cells;
      const v = frame.view;
      let html = '';
      let primes = 0;
      for (let k = 2; k <= n; k += 1) {
        const s = cells[k] || 0;
        if (s === 1) primes += 1;
        const cls = ['cell'];
        if (s === 1) cls.push('prime');
        if (s === 2) cls.push('composite');
        if (v.m === k) cls.push('mark');
        if (v.p === k) cls.push('sel');
        html += `<div class="cell-wrap"><div class="${cls.join(' ')}">${k}</div></div>`;
      }
      root.innerHTML = `<div class="row between" style="margin-bottom:12px"><span class="chip accent">${typeof v.p === 'number' ? `sieving with p = ${v.p}` : 'sieve of Eratosthenes'}</span><span class="chip teal">${primes} prime${primes === 1 ? '' : 's'} confirmed</span></div><div class="cells sieve">${html}</div>`;
    }
  };
}

const RENDERERS = { bars: barsRenderer, cells: cellsRenderer, graph: graphRenderer, structure: structureRenderer, calltree: callTreeRenderer, gcd: gcdRenderer, sieve: sieveRenderer };

export function createRenderer(kind, root, ctx) {
  const factory = RENDERERS[kind] || barsRenderer;
  return factory(root, ctx);
}

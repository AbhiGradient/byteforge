import { icon } from '../icons.js';
import { api } from '../api.js';
import { esc, skeleton } from '../util.js';
import { highlightBlock } from '../highlight.js';
import { renderMarkdown } from '../markdown.js';
import { addQuizResult, getQuizHistory } from '../store.js';

const LEVELS = [
  ['beginner', 'Beginner', 'Definitions, basic behaviour and simple tracing.'],
  ['intermediate', 'Intermediate', 'Comparing algorithms, tracing and choosing the right tool.'],
  ['advanced', 'Advanced', 'Edge cases, complexity arguments and subtle implementation details.']
];
const TYPES = [['mcq', 'Multiple choice'], ['code', 'Code based'], ['conceptual', 'Conceptual'], ['complexity', 'Complexity'], ['application', 'Applications']];
const TYPE_LABEL = Object.fromEntries(TYPES);

export default async function mount(root) {
  const catalog = await api.catalog();
  const state = { difficulty: 'beginner', topic: 'all', count: 5, types: new Set(TYPES.map(([k]) => k)) };
  let quiz = null;
  let dead = false;

  /* ----------------------------- setup ----------------------------------- */
  function setup(error = '') {
    const history = getQuizHistory().slice(0, 5);
    root.innerHTML = `
      <div class="page-head"><div><div class="eyebrow">${icon('viva')} VIVA ARENA</div><h1>Test yourself like it is the real viva</h1><p>The AI examiner writes fresh questions about the BYTEFORGE algorithm library. Pick a level, a topic and the kinds of questions you want.</p></div></div>
      ${error ? `<div class="notice error" style="margin-bottom:var(--gap)"><div><strong>${esc(error)}</strong></div></div>` : ''}
      <div class="grid cols-2" style="grid-template-columns:minmax(0,3fr) minmax(0,2fr)">
        <div class="stack">
          <div class="card"><div class="card-head"><h3>1. Difficulty</h3></div>
            <div class="grid cols-3">${LEVELS.map(([k, l, d]) => `<button class="diff-card ${state.difficulty === k ? 'on' : ''}" data-diff="${k}"><h3>${l}</h3><p>${d}</p></button>`).join('')}</div></div>
          <div class="card"><div class="card-head"><h3>2. Topic and length</h3></div>
            <div class="input-grid">
              <div class="field"><label for="topic">Topic</label><select id="topic" class="select"><option value="all">Whole library</option>${Object.entries(catalog.categories).map(([k, l]) => `<optgroup label="${esc(l)}"><option value="${k}" ${state.topic === k ? 'selected' : ''}>All ${esc(l)}</option>${catalog.algorithms.filter((a) => a.category === k).map((a) => `<option value="${a.id}" ${state.topic === a.id ? 'selected' : ''}>${esc(a.name)}</option>`).join('')}</optgroup>`).join('')}</select></div>
              <div class="field"><label for="count">Questions</label><select id="count" class="select">${[3, 5, 8, 10].map((n) => `<option ${n === state.count ? 'selected' : ''}>${n}</option>`).join('')}</select></div>
            </div></div>
          <div class="card"><div class="card-head"><h3>3. Question types</h3></div>
            <div class="row" id="types">${TYPES.map(([k, l]) => `<button class="chip ${state.types.has(k) ? 'on' : ''}" data-type="${k}">${l}</button>`).join('')}</div></div>
          <div class="row"><button class="btn primary" id="start">${icon('bolt')} Generate questions</button><span class="hint">Questions are generated by Gemini on the server and checked before you see them.</span></div>
        </div>
        <div class="card"><div class="card-head"><h3>${icon('clock')} Recent attempts</h3></div>
          ${history.length ? history.map((h) => `<div class="row between" style="padding:8px 0;border-bottom:1px solid var(--border)"><div><strong>${esc(h.scope || 'Library')}</strong><div class="faint" style="font-size:.78rem">${esc(h.difficulty)} · ${new Date(h.ts).toLocaleDateString()}</div></div><span class="chip ${h.score / h.total >= 0.7 ? 'teal' : 'warn'}">${h.score}/${h.total}</span></div>`).join('') : '<p class="muted" style="margin:0">No attempts yet. Your results are stored only in this browser.</p>'}
        </div>
      </div>`;
    root.querySelectorAll('[data-diff]').forEach((b) => b.addEventListener('click', () => { state.difficulty = b.dataset.diff; root.querySelectorAll('[data-diff]').forEach((x) => x.classList.toggle('on', x === b)); }));
    root.querySelector('#topic').addEventListener('change', (e) => { state.topic = e.target.value; });
    root.querySelector('#count').addEventListener('change', (e) => { state.count = Number(e.target.value); });
    root.querySelectorAll('[data-type]').forEach((b) => b.addEventListener('click', () => {
      const k = b.dataset.type;
      if (state.types.has(k) && state.types.size === 1) return;
      state.types.has(k) ? state.types.delete(k) : state.types.add(k);
      b.classList.toggle('on', state.types.has(k));
    }));
    root.querySelector('#start').addEventListener('click', generate);
  }

  async function generate() {
    root.innerHTML = `<div class="page-head"><div><div class="eyebrow">${icon('viva')} VIVA ARENA</div><h1>Preparing your questions...</h1><p>The examiner is writing ${state.count} ${state.difficulty} questions.</p></div></div><div class="card">${skeleton(8)}</div>`;
    try {
      const data = await api.viva({ difficulty: state.difficulty, topic: state.topic, count: state.count, types: [...state.types] });
      if (dead) return;
      begin(data.questions, data);
    } catch (err) {
      if (!dead) setup(err.message);
    }
  }

  /* ----------------------------- quiz ------------------------------------ */
  function begin(questions, meta) {
    quiz = { questions, meta, index: 0, answers: [], locked: false };
    question();
  }

  function question() {
    const q = quiz.questions[quiz.index];
    const total = quiz.questions.length;
    const answered = quiz.answers[quiz.index];
    root.innerHTML = `
      <div class="page-head"><div><div class="eyebrow">${icon('viva')} ${esc(quiz.meta.scope)} · ${esc(quiz.meta.difficulty)}</div><h1>Question ${quiz.index + 1} of ${total}</h1></div>
        <div class="row"><span class="chip accent">${esc(TYPE_LABEL[q.type] || 'Question')}</span><span class="chip">${esc(q.topic)}</span><span class="chip teal">score ${quiz.answers.filter((a, i) => a === quiz.questions[i].answerIndex).length}</span></div></div>
      <div class="bar-track" style="margin-bottom:var(--gap)"><i style="width:${(quiz.index / total) * 100}%"></i></div>
      <div class="card" style="max-width:860px">
        <h2 style="font-size:1.12rem;line-height:1.5;margin-bottom:12px">${esc(q.question)}</h2>
        ${q.code ? `<div class="codeblock md" style="margin-bottom:14px;border:1px solid var(--border);border-radius:10px;background:var(--code-bg);overflow:auto"><pre style="margin:0;padding:12px 14px;font-size:.84rem;line-height:1.55"><code>${highlightBlock(q.code, 'cpp')}</code></pre></div>` : ''}
        <div class="stack" style="gap:10px" id="opts">${q.options.map((o, i) => `<button class="option" data-i="${i}" ${answered !== undefined ? 'disabled' : ''}><span class="letter">${'ABCD'[i]}</span><span>${esc(o)}</span></button>`).join('')}</div>
        <div id="feedback" style="margin-top:16px"></div>
      </div>`;
    if (answered !== undefined) reveal(answered);
    root.querySelectorAll('.option').forEach((b) => b.addEventListener('click', () => {
      if (quiz.answers[quiz.index] !== undefined) return;
      quiz.answers[quiz.index] = Number(b.dataset.i);
      reveal(Number(b.dataset.i));
    }));
  }

  function reveal(choice) {
    const q = quiz.questions[quiz.index];
    const ok = choice === q.answerIndex;
    root.querySelectorAll('.option').forEach((b) => {
      const i = Number(b.dataset.i);
      b.disabled = true;
      if (i === q.answerIndex) b.classList.add('correct');
      else if (i === choice) b.classList.add('wrong');
    });
    const last = quiz.index === quiz.questions.length - 1;
    root.querySelector('#feedback').innerHTML = `<div class="notice ${ok ? 'info' : 'error'}" style="align-items:flex-start"><div><strong>${ok ? 'Correct.' : `Not quite. The correct answer is ${'ABCD'[q.answerIndex]}.`}</strong><div style="margin-top:6px">${renderMarkdown(q.explanation)}</div></div></div>
      <div class="row" style="margin-top:14px"><button class="btn primary" id="nextQ">${last ? 'See my report' : 'Next question'} ${icon('arrowRight')}</button></div>`;
    root.querySelector('#nextQ').addEventListener('click', () => { if (last) report(); else { quiz.index += 1; question(); } });
  }

  /* ----------------------------- report ---------------------------------- */
  function report(save = true) {
    const total = quiz.questions.length;
    const score = quiz.answers.filter((a, i) => a === quiz.questions[i].answerIndex).length;
    const pct = Math.round((score / total) * 100);
    if (save && !quiz.saved) {
      addQuizResult({ score, total, difficulty: quiz.meta.difficulty, topic: quiz.meta.topic, scope: quiz.meta.scope });
      quiz.saved = true;
    }
    const byType = {};
    quiz.questions.forEach((q, i) => {
      byType[q.type] = byType[q.type] || { ok: 0, n: 0 };
      byType[q.type].n += 1;
      if (quiz.answers[i] === q.answerIndex) byType[q.type].ok += 1;
    });
    const grade = pct >= 90 ? 'Outstanding. You are viva ready.' : pct >= 70 ? 'Good work. Review the missed questions below.' : pct >= 50 ? 'A fair start. Revisit the topics you missed.' : 'Keep practising. Read the explanations and try again.';
    root.innerHTML = `
      <div class="page-head"><div><div class="eyebrow">${icon('viva')} Final report</div><h1>${esc(grade)}</h1></div></div>
      <div class="grid cols-2" style="grid-template-columns:minmax(0,1fr) minmax(0,2fr);margin-bottom:var(--gap)">
        <div class="card row" style="justify-content:center;gap:24px"><div class="score-ring" style="--p:${pct}"><b>${pct}%</b></div><div class="stat"><span class="v">${score}/${total}</span><span class="l">correct answers</span></div></div>
        <div class="card"><div class="card-head"><h3>By question type</h3></div>${Object.entries(byType).map(([t, v]) => `<div style="margin-bottom:10px"><div class="row between"><span>${esc(TYPE_LABEL[t] || t)}</span><span class="mono">${v.ok}/${v.n}</span></div><div class="bar-track"><i style="width:${(v.ok / v.n) * 100}%"></i></div></div>`).join('')}</div>
      </div>
      <div class="row" style="margin-bottom:var(--gap)"><button class="btn primary" id="retry">${icon('refresh')} Retry these questions</button><button class="btn" id="fresh">${icon('shuffle')} New questions</button><button class="btn ghost" id="setup">Change settings</button></div>
      <div class="stack">${quiz.questions.map((q, i) => { const ok = quiz.answers[i] === q.answerIndex; return `<div class="card"><div class="row between"><strong>Q${i + 1}. ${esc(q.question)}</strong><span class="chip ${ok ? 'teal' : 'danger'}">${ok ? 'correct' : 'incorrect'}</span></div>
        <p class="muted" style="margin:8px 0 4px">Your answer: <strong>${quiz.answers[i] === undefined ? 'not answered' : esc(q.options[quiz.answers[i]])}</strong>${ok ? '' : ` · Correct: <strong>${esc(q.options[q.answerIndex])}</strong>`}</p>${renderMarkdown(q.explanation)}</div>`; }).join('')}</div>`;
    root.querySelector('#retry').addEventListener('click', () => { quiz.index = 0; quiz.answers = []; quiz.saved = false; quiz.questions = quiz.questions.map((q) => shuffleOptions(q)); question(); });
    root.querySelector('#fresh').addEventListener('click', generate);
    root.querySelector('#setup').addEventListener('click', () => setup());
  }

  function shuffleOptions(q) {
    const idx = q.options.map((_, i) => i).sort(() => Math.random() - 0.5);
    return { ...q, options: idx.map((i) => q.options[i]), answerIndex: idx.indexOf(q.answerIndex) };
  }

  setup();
  return () => { dead = true; };
}
